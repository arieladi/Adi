def engine_builder(p, ctx):
    """
    pfft~ instances are created by `thispatcher script newdefault`, driven from
    message boxes -- NOT by patcher.newdefault() from JS.

    pfft~ takes its FFT size as a creation argument and wants an int.  Numbers
    handed to newdefault() from JS did not arrive as ints, so pfft~ fell back to
    its documented default of 512: the analysis ran at 512 while the reduction
    believed 4096, and the whole spectrum was compressed 8x into the bottom
    2.7 kHz with every level read from 8x the intended frequency.  Arguments
    typed into a message box are parsed by Max itself, so the size is a genuine
    int.  The subpatch also reports the frame size it ACTUALLY got (#0_rpt), and
    the reduction is configured from that rather than from what was asked for,
    so a mismatch can never silently distort the display again.
    """
    X, Y = 20, 2350
    p.comment("ENGINE BUILDER -- pfft~ built from typed script messages so the "
              "FFT size arrives as an int", X, Y - 22, fontsize=11)

    # slot 3 is the fftin~ envelope name; a symbol, so pack is typed by it
    pk = p.obj("pack 4096 4 2048 hanning", X, Y + 130, nin=4)

    szsel = p.obj("sel 0 1 2 3 4", X, Y)
    p.connect(ctx["mBlock"], 0, szsel, 0)
    szt = p.obj("t i i", X, Y + 66)
    for i, n in enumerate(BLOCKS):
        m = p.msg(str(n), X + i * 72, Y + 33, w=62)
        p.connect(szsel, i, m, 0)
        p.connect(m, 0, szt, 0)
    half = p.obj("/ 2", X + 150, Y + 98)
    p.connect(szt, 1, half, 0)      # right outlet first: frame size, cold
    p.connect(half, 0, pk, 2)
    p.connect(szt, 0, pk, 0)        # then the size, hot -> emits the triple

    ovt = p.obj("t b i", X + 470, Y - 30)
    p.connect(ctx["mOvl"], 0, ovt, 0)
    ovsel = p.obj("sel 0 1", X + 470, Y)
    p.connect(ovt, 1, ovsel, 0)
    for i, n in enumerate((4, 8)):
        m = p.msg(str(n), X + 470 + i * 56, Y + 33, w=48)
        p.connect(ovsel, i, m, 0)
        p.connect(m, 0, pk, 1)
    reask = p.msg("outputvalue", X + 600, Y + 33)
    p.connect(ovt, 0, reask, 0)     # overlap is cold: re-emit the block size
    p.connect(reask, 0, ctx["mBlock"], 0)

    # Window is an fftin~ creation argument, so changing it rebuilds the engine
    # exactly as block size and overlap do.  Same idiom: set the cold slot,
    # then re-emit the block size to fire the build.
    wt = p.obj("t b i", X + 470, Y + 96)
    p.connect(ctx["mWin"], 0, wt, 0)
    wsel = p.obj("sel 0 1 2", X + 470, Y + 126)
    p.connect(wt, 1, wsel, 0)
    for i, nm in enumerate(("hanning", "hamming", "blackman")):
        m = p.msg(nm, X + 470 + i * 86, Y + 156, w=78)
        p.connect(wsel, i, m, 0)
        p.connect(m, 0, pk, 3)
    wreask = p.msg("outputvalue", X + 740, Y + 126)
    p.connect(wt, 0, wreask, 0)
    p.connect(wreask, 0, ctx["mBlock"], 0)

    seq = p.obj("t l l l l", X, Y + 165)
    p.connect(pk, 0, seq, 0)
    tp = p.obj("thispatcher", X, Y + 330)

    off = p.obj("prepend enginesoff", X + 640, Y + 200)
    p.connect(seq, 3, off, 0)
    p.connect(off, 0, ctx["engine"], 0)

    for tag, yy, dy in (("A", 40, 0), ("B", 90, 30)):
        mk = p.msg("script newdefault avcEng%s 40 %d pfft~ avc.fftanalysis "
                   "$1 $2 0 0 args #0_spec%s #0_ctl%s $3 #0_rpt $4"
                   % (tag, yy, tag, tag), X, Y + 200 + dy, w=600)
        p.connect(seq, 2, mk, 0)
        p.connect(mk, 0, tp, 0)

    con = p.msg("script connect srcA 0 avcEngA 0, "
                "script connect srcB 0 avcEngB 0", X, Y + 265, w=600)
    p.connect(seq, 1, con, 0)
    p.connect(con, 0, tp, 0)

    post = p.msg("postbuild", X + 640, Y + 265)
    p.connect(seq, 0, post, 0)
    p.connect(post, 0, ctx["engine"], 0)

    rpt = p.obj("r #0_rpt", X + 640, Y)
    rr = p.obj("route framesize", X + 640, Y + 33)
    p.connect(rpt, 0, rr, 0)
    fp = p.obj("prepend framesize", X + 640, Y + 66)
    p.connect(rr, 0, fp, 0)
    p.connect(fp, 0, ctx["engine"], 0)


