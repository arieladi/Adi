UNITSTYLE_INT, UNITSTYLE_FLOAT = 0, 1


def add_num(p, ctx, px, w, row_y, varname, longname, short, lo, hi, default,
            col, is_int=False):
    """
    Every numeric parameter is declared as Live type FLOAT, never Int.

    Live's native integer representation is limited to 256 values: declaring
    parameter_type 1 makes Live silently rewrite mmax to mmin+255, so a
    10..5000 ms control became 10..265 and a 3000..48000 Hz control became
    3000..3255 -- which is why the spectrum could never show past 3 kHz.
    Max's own documentation prescribes exactly this: "the Type attribute should
    be set to Float, and the Unit Style attribute should be set to Int."

    `is_int` therefore selects the DISPLAY style, not the data type.
    """
    o = p.ui("live.numbox", 40 + col * 150, _PY[0], w, CTRL_H, nout=2,
             presentation=1, presentation_rect=[px, row_y, w, CTRL_H],
             fontsize=8.0)
    p.param(o, longname, short, 0, mmin=float(lo), mmax=float(hi),
            initial=float(default),
            unitstyle=UNITSTYLE_INT if is_int else UNITSTYLE_FLOAT)
    return _place_common(p, ctx, varname, o, longname)


