def menu_map(p, ctx, key, values, target, prefix=None, inlet=0, x=0, y=0):
    """`target` may be one box or a list of (box, inlet) pairs."""
    """
    Map a live.menu index to a value with `sel` plus message boxes.

    This replaces `expr <cond> ? a : b`.  Max's expr has no ternary operator, so
    those objects never output anything and everything downstream of them --
    the meter channel selectors, correlation, FPS, overlap and smoothing --
    sat at its creation-time default forever.
    """
    targets = target if isinstance(target, list) else [(target, inlet)]
    src = ctx[key]
    s = p.obj("sel " + " ".join(str(i) for i in range(len(values))), x, y)
    p.connect(src, 0, s, 0)
    sink = None
    if prefix:
        sink = p.obj("prepend " + prefix, x, y + 62)
        for tgt, inl in targets:
            p.connect(sink, 0, tgt, inl)
    for i, v in enumerate(values):
        m = p.msg(str(v), x + i * 64, y + 30, w=56)
        p.connect(s, i, m, 0)
        if sink is not None:
            p.connect(m, 0, sink, 0)
        else:
            for tgt, inl in targets:
                p.connect(m, 0, tgt, inl)
    return s


def param_wiring(p, ctx):
    ui, eng, mts = ctx["ui"], ctx["engine"], ctx["metersjs"]
    X, Y = 1350, 1240
    row = [0]

    def to(key, prefix, target, transform=None):
        y = Y + row[0] * 26
        row[0] += 1
        cur = ctx[key]
        if transform:
            t = p.obj(transform, X + 180, y)
            p.connect(cur, 0, t, 0)
            cur = t
        pre = p.obj("prepend " + prefix, X + 520, y)
        p.connect(cur, 0, pre, 0)
        p.connect(pre, 0, target, 0)

    # --- spectrum engine ---
    to("mWin", "wintype", eng)
    to("nAvg", "avgtime", eng)
    to("nSlope", "slope", eng)
    menu_map(p, ctx, "mSmooth", [0., 0.0833, 0.1667, 0.3333, 0.5, 1.],
             eng, prefix="smooth", x=1350, y=2500)
    to("tAlign", "align", eng)
    to("nFlo", "freqlo", eng)
    to("nFhi", "freqhi", eng)
    to("mType1", "typepri", eng)
    to("mType2", "typesec", eng)

    # --- display ---
    for key, msg in (("nRlo", "rangelo"), ("nRhi", "rangehi"),
                     ("nFlo", "freqlo"), ("nFhi", "freqhi"),
                     ("tFill", "filled"), ("tSecond", "second"),
                     ("tAA", "antialias"), ("tCross", "crosshair"),
                     ("tBig", "largereadout"), ("tHideM", "hidemeters"),

                     ("nRefA", "refpitch"), ("mOffset", "offsetmode"),
                     ("mMode", "metermode"), ("mScope", "scopecolour")):
        to(key, msg, ui)

    # --- meters ---
    for key, msg in (("mWeight", "weight"), ("nInteg", "integration"),
                     ("nRel", "release"), ("nPkHold", "peakhold"),
                     ("mBias", "bias")):
        to(key, msg, mts)

    meters_return(p, ctx)
    engine_return(p, ctx)
    channel_routing(p, ctx)
    misc_wiring(p, ctx)


def meters_return(p, ctx):
    X, Y = 1350, 1700
    mts, ui = ctx["metersjs"], ctx["ui"]
    r = p.obj("route pkhold bias meterscale rmswin rms50win pkslide kfixed "
              "corrslide balslide", X, Y)
    p.connect(mts, 0, r, 0)

    # Hold time goes to each timer's RIGHT inlet: the left inlet would both set
    # the time and start the timer.
    for k in ("hPkL", "hPkR", "hRmsL", "hRmsR"):
        p.connect(r, 0, ctx[k]["delay"], 1)

    # metering bias offset and scale span are display concerns
    bp = p.obj("prepend bias", X + 200, Y + 30)
    p.connect(r, 1, bp, 0)
    p.connect(bp, 0, ui, 0)
    sp = p.obj("prepend meterscale", X + 340, Y + 30)
    p.connect(r, 2, sp, 0)
    p.connect(sp, 0, ui, 0)

    # RMS window lengths, in samples, coerced to int on the way in.
    #
    # average~'s documented methods are int / absolute / bipolar / rms /
    # signal -- there is NO float method.  A float window is therefore not
    # rounded, it is REJECTED, and an interval larger than the creation
    # argument is discarded silently as well.  Either way the object keeps
    # the interval its creation argument installed: 192000 samples, i.e. a
    # 4.35 s window at 44.1 kHz instead of the 300 ms asked for.  A 4 s RMS
    # reads several dB below a 300 ms RMS on programme material, by an amount
    # that varies with the material -- exactly the error measured against
    # bx_meter, and exactly why it did not look like a constant offset.
    # The LUFS path already coerces this way; the RMS path did not.
    wI = p.obj("expr int($f1)", X + 520, Y + 30)
    p.connect(r, 3, wI, 0)
    for o in ctx["rmswin"]:
        p.connect(wI, 0, o, 0)
    w50I = p.obj("expr int($f1)", X + 660, Y + 30)
    p.connect(r, 4, w50I, 0)
    for o in ctx["rms50win"]:
        p.connect(w50I, 0, o, 0)
    # correlation / balance integrators: same value to slide-up and slide-down,
    # so each is a symmetric one-pole whose time constant tracks the sample rate.
    for o in ctx["corrSlides"]:
        p.connect(r, 7, o, 1)
        p.connect(r, 7, o, 2)
    for o in ctx["balSlides"]:
        p.connect(r, 8, o, 1)
        p.connect(r, 8, o, 2)

    # peak-bar ballistics -> slide~ up/down inlets
    up = p.obj("unpack 0. 0.", X + 760, Y + 30, nout=2)
    p.connect(r, 5, up, 0)
    for n in ("pkSlideL", "pkSlideR"):
        o = ctx["slides"][n]
        p.connect(up, 0, o, 1)
        p.connect(up, 1, o, 2)


def engine_return(p, ctx):
    X, Y = 1350, 1780
    r = p.obj("route nyquist diag", X, Y)
    p.connect(ctx["engine"], 0, r, 0)
    n = p.obj("prepend nyquist", X, Y + 30)
    p.connect(r, 0, n, 0)
    p.connect(n, 0, ctx["ui"], 0)
    dg = p.obj("prepend diag", X + 220, Y + 30)
    p.connect(r, 1, dg, 0)
    p.connect(dg, 0, ctx["ui"], 0)

    # Not visible -> the redraw clock drops to 5 Hz.  It used to be STOPPED, and
    # that is measurably worse: the display took most of a second to come back
    # while the clock restarted and the analysis refilled, and it bought nothing
    # -- Live's CPU meter reads the audio thread, and drawing is not on it.  A
    # slow heartbeat keeps everything warm, so returning is instant.
    vsel = p.obj("sel 0 1", X + 240, Y + 60, nout=3)
    p.connect(ctx["visible"], 0, vsel, 0)
    slowv = p.msg("200", X + 240, Y + 90, w=44)
    p.connect(vsel, 0, slowv, 0)
    p.connect(slowv, 0, ctx["metro"], 1)
    # Arriving back at this track clears the accumulated history, exactly as if
    # the Reset button had been pressed.  Coming back used to show the frozen
    # last frame from before you left while the engines refilled, which reads as
    # the display being stuck.  This also clears the Max hold, which is the one
    # thing worth knowing: a hold you deliberately left accumulating does not
    # survive a trip to another track.
    p.connect(vsel, 1, ctx["resetTrigger"], 0)

    vt = p.obj("t b i", X + 240, Y + 120, nout=2)
    p.connect(ctx["visible"], 0, vt, 0)
    p.connect(vt, 1, ctx["gVisible"], 0)   # control first
    p.connect(vt, 0, ctx["gVisible"], 1)   # then try to restore, AND-ed with awake

    # The device's own power switch.  live.thisdevice's MIDDLE outlet sends 1
    # when the device is enabled and 0 when it is disabled, and it keeps sending
    # while the device is off -- which is the whole reason self-reactivation is
    # possible at all, and is how Ableton's own BeatSeeker works.  Live has
    # already removed the MSP by then; what is left to stop is the drawing.
    #
    # SLOW it, do not STOP it.  A gate here closed the frame chain completely,
    # and that turned every way the power switch could get stuck into a device
    # with a permanently BLANK display -- no plot, no meters, no settings screen,
    # so not even a way to reach the Auto toggle and turn the behaviour off.
    # That is exactly what happened: the self-switch could not re-enable the
    # device ("set: no valid object set" in Live's log), and the gate left
    # nothing on screen to diagnose it with.  A 2 Hz heartbeat keeps 95% of the
    # saving and cannot strand anyone.
    esel = p.obj("sel 0 1", X + 700, Y + 120, nout=3)
    p.connect(ctx["thisdevice"], 1, esel, 0)
    eslow = p.msg("500", X + 700, Y + 150, w=44)
    p.connect(esel, 0, eslow, 0)
    p.connect(eslow, 0, ctx["metro"], 1)
    p.connect(esel, 1, ctx["fpsRestore"], 0)

    # Auto owns the self-switch gate.  Wired here rather than in the visibility
    # block because the control does not exist yet at that point.
    p.connect(ctx["tAuto"], 0, ctx["autoGate"], 0)

    for pre in ctx.get("dbgTaps", []):
        p.connect(pre, 0, ctx["ui"], 0)

    vpre = p.obj("prepend visible", X, Y + 90)
    p.connect(ctx["visible"], 0, vpre, 0)
    p.connect(vpre, 0, ctx["engine"], 0)


def channel_routing(p, ctx):
    """
    Channel mode and Underlay together choose the two engine sources.
    index = channel + 6 * underlay.  Underlay overlays the complementary
    channel group, which is the pairing that is actually useful (L against R,
    Mid against Side) and needs no extra menu.
    Triple is: srcA index, srcB index, jsui engine-B mode (0 off, 1 overlaid,
    2 underlay).
    """
    X, Y = 20, 1900
    p.comment("CHANNEL / UNDERLAY ROUTING", X, Y - 22, fontsize=11)
    # $i, not $f: `select` with integer arguments does not match a float,
    # so a float here would leave both selector~ objects at 0 (silence).
    comb = p.obj("expr $i1 + 6*$i2", X, Y, nin=2)
    p.connect(ctx["mChan"], 0, comb, 0)
    # comb's right inlet is cold, so Underlay alone would not recompute the
    # routing; re-emit the channel value whenever Underlay changes.
    ut = p.obj("t b i", X + 260, Y - 30)
    p.connect(ctx["tUnder"], 0, ut, 0)
    p.connect(ut, 1, comb, 1)
    reask = p.msg("outputvalue", X + 380, Y - 30)
    p.connect(ut, 0, reask, 0)
    p.connect(reask, 0, ctx["mChan"], 0)
    sel = p.obj("sel " + " ".join(str(i) for i in range(12)), X, Y + 30, nout=13)
    p.connect(comb, 0, sel, 0)

    routes = [
        (1, 0, 0), (2, 0, 0), (3, 0, 0), (2, 3, 1), (4, 0, 0), (5, 0, 0),
        (1, 5, 2), (2, 3, 2), (3, 2, 2), (2, 3, 1), (4, 5, 2), (5, 4, 2),
    ]
    for i, (a, b, mode) in enumerate(routes):
        m = p.msg("%d %d %d" % (a, b, mode), X + i * 100, Y + 60, w=62)
        p.connect(sel, i, m, 0)
        up = p.obj("unpack 0 0 0", X + i * 100, Y + 90, nout=3)
        p.connect(m, 0, up, 0)
        p.connect(up, 0, ctx["srcA"], 0)
        p.connect(up, 1, ctx["srcB"], 0)
        eb = p.obj("prepend engineb", X + i * 100, Y + 120)
        p.connect(up, 2, eb, 0)
        p.connect(eb, 0, ctx["ui"], 0)
        # The ENGINE needs this too.  It never got it, so engine B's pfft~ ran
        # permanently -- in the default Sum mode its source is silence, so half
        # the FFT work in the device was transforming nothing.
        p.connect(eb, 0, ctx["engine"], 0)
        p.connect(up, 2, ctx["engBused"], 0)


def misc_wiring(p, ctx):
    X, Y = 20, 2080
    # Meter mode -> metering source selectors. Stereo and Link both meter
    # L/R (selector~ input 1); M/S meters Mid/Side (input 2).
    menu_map(p, ctx, "mMode", [1, 2],
             [(ctx["mtrL"], 0), (ctx["mtrR"], 0)], x=X, y=Y)

    # FPS -> metro interval, parked in `f` so the idle gate can restore it.
    fpsf = p.obj("f 25", X, Y + 130)
    menu_map(p, ctx, "mFps", [66, 33, 25, 16], [(fpsf, 0)], x=X + 340, y=Y)
    p.connect(ctx["fpsRestore"], 0, fpsf, 0)
    p.connect(fpsf, 0, ctx["metro"], 1)

    # The Width menu is gone.  It sent `size 420|960|1440 155` to thispatcher,
    # but the jsui's presentation rect is fixed at 960x155, so the drawing never
    # followed the frame: Compact shrank the window and left the meter block
    # painting ~470 px outside it, and Wide drew exactly what Normal drew with a
    # blank strip beside it.  Only one of its three values was ever correct.

    rsel = p.obj("sel 1", X + 640, Y + 40)
    p.connect(ctx["bReset"], 0, rsel, 0)
    p.connect(rsel, 0, ctx["resetTrigger"], 0)
    p.connect(ctx["mPreset"], 0, ctx["presetSel"], 0)
    settings_panel(p, ctx)


def settings_panel(p, ctx):
    """
    The parameter rows are ordinary live.* objects overlaying the bottom of the
    jsui; `thispatcher`'s `script hide` / `script show` toggles them, which is
    the one mechanism that works without moving anything or duplicating state.
    They remain live parameters while hidden, so presets and stored values are
    unaffected by whether the panel happens to be open.
    """
    X, Y = 20, 2200
    p.comment("SETTINGS PANEL -- show/hide the parameter rows", X, Y - 22,
              fontsize=11)
    names = [o.d["varname"] for o in ctx["panelControls"]]
    show = p.msg(", ".join("script show " + n for n in names), X, Y, w=680)
    hide = p.msg(", ".join("script hide " + n for n in names), X, Y + 30, w=680)
    tp = p.obj("thispatcher", X, Y + 60)
    p.connect(show, 0, tp, 0)
    p.connect(hide, 0, tp, 0)

    # View 5 IS the settings screen: the controls are shown with it and hidden
    # with it, so there is nothing floating over a display and nothing to
    # dismiss -- picking any other view leaves it.
    isset = p.obj("== 5", X + 720, Y - 60)
    p.connect(ctx["mView"], 0, isset, 0)
    sel = p.obj("sel 1 0", X + 720, Y - 30)
    p.connect(isset, 0, sel, 0)
    p.connect(sel, 0, show, 0)
    p.connect(sel, 1, hide, 0)

    vm = p.obj("prepend viewmode", X + 940, Y + 60)
    p.connect(ctx["mView"], 0, vm, 0)
    p.connect(vm, 0, ctx["ui"], 0)
    # the engine mutes both pfft~ while the analyser is hidden
    p.connect(vm, 0, ctx["engine"], 0)

    # The scope sweep is locked to the bar: plugsync~ reports Live's bar count
    # and the sweep's phase is reset to 0 whenever it changes, so the downbeat
    # always lands on the left edge.  The reset arrives at the wrap, where the
    # ramp already jumps, so it is invisible.
    #
    # This used to be GATED on the scope being the visible view, and that is why
    # it appeared not to sync.  Nothing was tracking the bar while you were on
    # another screen, and the capture voice is muted there too, so switching to
    # OSC resumed a free-running phasor~ at whatever phase it happened to hold
    # -- the sweep started somewhere in the middle of the screen and stayed
    # wrong until the next bar came round.  Polling costs one bang a frame into
    # plugsync~; muting the voice does not stop it accepting the message, so
    # the phase is already correct by the time the view appears.
    ps = p.obj("plugsync~", X + 720, Y + 126, nout=9)
    p.connect(ctx["frameT"], 2, ps, 0)
    bch = p.obj("change -1", X + 720, Y + 156)
    p.connect(ps, 1, bch, 0)                 # outlet 1 = current bar count
    zmsg = p.msg("phase 0", X + 720, Y + 186, w=64)
    p.connect(bch, 0, zmsg, 0)
    p.connect(zmsg, 0, ctx["capscope"], 2)   # -> phasor~ phase inlet in the voice

    # ...and once more the moment the transport starts.  The bar count often
    # does not CHANGE on the first play -- you are usually still in the bar you
    # stopped in -- so `change` alone stays silent exactly when the alignment
    # matters most, which is the first downbeat the user sees.
    p.connect(ctx["playing"], 0, zmsg, 0)

    # While the panel is open, poll the engine for its self-measurement once a
    # second and show it on the panel.  This is the one readout that says what
    # the analysis is ACTUALLY doing, without unlocking the device in Max.
    # Runs from load, not only while the panel is open: the readout it feeds is
    # drawn whenever the cursor is not over the plot, so it is always available.
    # A `metro 1000` used to sit here asking the engine for `diag` once a
    # second, forever.  That handler walks EVERY bin with getcell() -- 8192 of
    # them at the largest block size -- packs seventeen values and sends them to
    # the jsui, where drawing them is gated behind a flag that nothing in this
    # patch has ever set.  Permanently invisible, permanently paid for.


