# 3. Spectrum display chain
# ---------------------------------------------------------------------------
def spectrum_chain(p, ctx):
    X, Y = 20, 320
    p.comment("SPECTRUM REDUCTION -- the 5-plane analysis matrix is written by "
              "jit.poke~ inside the pfft~; planemap picks the two selected "
              "analysis types; jit.gen reduces to one point per pixel; jit.spill "
              "hands one list per curve to jsui.", X, Y - 22, fontsize=11)

    spills = {}
    for i, tag in enumerate(("A", "B")):
        xo = X + i * 500
        mat = p.obj("jit.matrix #0_spec%s 5 float32 8192 1" % tag, xo, Y + 26)
        mat.d["varname"] = "mat" + tag      # cleared whenever engines rebuild
        sel = p.obj("jit.matrix 2 float32 8192 1 @planemap 1 2", xo, Y + 56)
        sel.d["varname"] = "sel" + tag
        geom = p.obj("jit.matrix 2 float32 600 1", xo + 270, Y + 56)
        geom.d["varname"] = "geom" + tag
        red = p.obj("jit.gen @gen avc.specreduce", xo, Y + 116, nin=2)
        red.d["varname"] = "red" + tag

        # the data (right) inlet must be loaded before the geometry (left)
        # inlet fires the gen, so t b b: right outlet first.
        trig = p.obj("t b b", xo, Y - 4)
        p.connect(trig, 1, mat, 0)
        p.connect(mat, 0, sel, 0)
        p.connect(sel, 0, red, 1)
        p.connect(trig, 0, geom, 0)
        p.connect(geom, 0, red, 0)

        for pl in (0, 1):
            sp = p.obj("jit.spill @plane %d @listlength 600" % pl,
                       xo, Y + 152 + pl * 34)
            sp.d["varname"] = "spill%s%d" % (tag, pl)
            p.connect(red, 0, sp, 0)
            pre = p.obj("prepend c%d" % (i * 2 + pl), xo + 300, Y + 152 + pl * 34)
            p.connect(sp, 0, pre, 0)
            spills["c%d" % (i * 2 + pl)] = pre
        ctx["spectrig" + tag] = trig
    ctx["spills"] = spills


