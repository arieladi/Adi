def init_sequence(p, ctx):
    """
    Nothing analyses or draws before live.thisdevice fires.  Order matters:
    configure the js helpers, then push every parameter value into them, then
    start the clock.
    """
    X, Y = 1350, 470
    td, eng, mts = ctx["thisdevice"], ctx["engine"], ctx["metersjs"]
    t = p.obj("t b b b b b", X, Y)
    p.connect(td, 0, t, 0)

    # 4 (first): resolve the Live transport path
    p.connect(t, 4, ctx["livepath"], 0)
    # 2: init both js helpers
    mi1 = p.msg("init", X, Y + 40)
    p.connect(t, 3, mi1, 0)
    p.connect(mi1, 0, eng, 0)
    mi2 = p.msg("init", X + 80, Y + 40)
    p.connect(t, 3, mi2, 0)
    p.connect(mi2, 0, mts, 0)
    # 2: report the sample rate, so the engines reconfigure for the real rate
    p.connect(t, 2, ctx["dspstate"], 0)
    # 1: push every stored parameter value out to its consumers
    ov = p.msg("outputvalue", X + 170, Y + 40)
    p.connect(t, 1, ov, 0)
    # The preset menu and the Reset button are deliberately excluded: re-emitting
    # the stored preset index at load would re-apply that preset and discard any
    # edits made after choosing it, and re-emitting Reset would clear on load.
    skip = {ctx["mPreset"].id, ctx["bReset"].id}
    for c in ctx["allControls"]:
        if c.id not in skip:
            p.connect(ov, 0, c, 0)
    # 0 (last): start the redraw clock
    mstart = p.msg("1", X + 320, Y + 40)
    p.connect(t, 0, mstart, 0)
    p.connect(mstart, 0, ctx["metro"], 0)
    ctx["metroStart"] = mstart


def samplerate_wiring(p, ctx):
    """
    Both js helpers need the running sample rate, and need it again whenever
    DSP restarts -- which is what happens when Live's rate changes.

    dspstate~ is the only source used here.  `adstatus sr` reports its numeric
    value on its RIGHT outlet (the left one carries `set` messages for a menu),
    which is an easy thing to get wrong, and dspstate~ already gives the value
    directly on outlet 1.
    """
    X, Y = 800, 530
    eng, mts = ctx["engine"], ctx["metersjs"]
    ds = p.obj("dspstate~", X, Y + 40, nin=2)
    ctx["dspstate"] = ds
    lb = p.obj("loadbang", X, Y)
    tb = p.obj("t b", X, Y + 14)
    p.connect(lb, 0, tb, 0)
    p.connect(tb, 0, ds, 0)           # report once at load
    edge = p.obj("t b", X + 200, Y + 14)
    p.connect(ds, 0, edge, 0)         # audio on/off -> report again
    p.connect(edge, 0, ds, 0)

    ch = p.obj("change 0", X, Y + 70)
    p.connect(ds, 1, ch, 0)           # outlet 1 is the sampling rate
    pre = p.obj("prepend samplerate", X, Y + 96)
    p.connect(ch, 0, pre, 0)
    p.connect(pre, 0, eng, 0)
    p.connect(pre, 0, mts, 0)

    # goniometer write index: one phasor~ cycle per 512 samples
    gdiv = p.obj("/ 512.", X + 200, Y + 96)
    p.connect(ch, 0, gdiv, 0)
    gpre = p.obj("prepend gsr", X + 200, Y + 122)
    p.connect(gdiv, 0, gpre, 0)
    p.connect(gpre, 0, ctx["capgonio"], 2)


    # LUFS windows are specified in seconds; average~ wants samples.
    mom, sht = ctx["lufsWin"]
    em = p.obj("expr int($f1*0.4)", X + 420, Y + 96)
    p.connect(ch, 0, em, 0)
    p.connect(em, 0, mom, 0)
    es = p.obj("expr int($f1*3.)", X + 620, Y + 96)
    p.connect(ch, 0, es, 0)
    p.connect(es, 0, sht, 0)


def frame_wiring(p, ctx):
    """One frame: spectrum first, then every meter snapshot, then pack and draw."""
    ft, ui = ctx["frameT"], ctx["ui"]
    # The spectrum reduction and the scope capture are mutually exclusive --
    # whichever display is hidden costs nothing, rather than both running and
    # one being thrown away.
    sg = p.obj("gate 1 1", 700, 1300)
    p.connect(ft, 2, sg, 1)
    p.connect(sg, 0, ctx["spectrigA"], 0)
    # engine B's reduction only feeds curves 2 and 3, which are drawn only when
    # engine B is in use; banging it otherwise spills two more lists a frame
    # for nothing.
    bg = p.obj("gate 1 0", 1020, 1300)
    p.connect(ft, 2, bg, 1)
    p.connect(bg, 0, ctx["spectrigB"], 0)
    bnz = p.obj("!= 0", 1020, 1270)
    ctx["engBused"] = bnz
    p.connect(bnz, 0, bg, 0)

    og = p.obj("gate 1 0", 860, 1300)
    p.connect(ft, 2, og, 1)
    p.connect(og, 0, ctx["scopeMat"], 0)
    # view 1 is the scope: it is the only view that does not need the analyser
    # reduction, and the only one that needs the scope capture read out.
    # Neither scope view needs the analyser reduction.
    inv = p.obj("expr ($i1 != 1) && ($i1 != 2)", 700, 1270)
    p.connect(ctx["mView"], 0, inv, 0)
    p.connect(inv, 0, sg, 0)
    isscope = p.obj("== 1", 860, 1270)
    ctx["isScope"] = isscope
    p.connect(ctx["mView"], 0, isscope, 0)
    p.connect(isscope, 0, og, 0)

    # view 2 is the fast scope, and it is the only one that reads the raw trace
    rg = p.obj("gate 1 0", 1180, 1300)
    p.connect(ft, 2, rg, 1)
    p.connect(rg, 0, ctx["rawMat"], 0)
    # views 2 (the fast scope) and 3 (RME, which now carries a period-locked
    # scope beside the bands) both read the raw trace
    israw = p.obj("expr ($i1 == 2) || ($i1 == 3)", 1180, 1270)
    p.connect(ctx["mView"], 0, israw, 0)
    p.connect(israw, 0, rg, 0)
    p.connect(ctx["scopeSpill"], 0, ui, 0)
    p.connect(ctx["rawSpill"], 0, ui, 0)
    for key in ("mL", "mR"):
        m = ctx[key]
        for s in ("peakBang", "peakSnap", "rmsSnap", "rms50Snap"):
            p.connect(ft, 1, m[s], 0)
    # Correlation and balance are computed by expr objects whose LEFT inlet is
    # hot.  Banging all five snapshots from one outlet leaves their order
    # undefined, so the expr fired on whatever had arrived: with ll and rr
    # still at zero, corr = lr / sqrt(1e-20) pins to +-1 and never moves --
    # which is exactly how it behaved.  t fires right to left, so the cold
    # terms are all delivered before the hot one triggers the calculation.
    cs = ctx["corrSnaps"]
    ct = p.obj("t b b b b b", 660, 1330)
    p.connect(ft, 1, ct, 0)
    for outi, key in ((4, "ll"), (3, "rr"), (2, "rrB"), (1, "llB"), (0, "lr")):
        p.connect(ct, outi, cs[key], 0)
    for s in ctx["lufsSnaps"]:
        p.connect(ft, 1, s, 0)

    for pre in ctx["spills"].values():
        p.connect(pre, 0, ui, 0)
    p.connect(ft, 2, ctx["gonioMat"], 0)
    for pre in ctx["gspills"]:
        p.connect(pre, 0, ui, 0)

    # Slot 19 is integrated LUFS, which this device does not compute (see
    # DEVIATIONS.md).  It used to be fed short-term LUFS a second time, which
    # presented a number that looked like an integrated reading and was not.
    # Left unconnected with a -144 creation default, so it reads as absent.
    packargs = ["0."] * 20
    packargs[19] = "-144."
    pk = p.obj("pack " + " ".join(packargs), 800, 1360, nin=20)
    order = [
        ctx["mL"]["peakBar"], ctx["mR"]["peakBar"],
        ctx["mL"]["rms"], ctx["mR"]["rms"],
        ctx["hPkL"]["out"], ctx["hPkR"]["out"],
        ctx["hRmsL"]["out"], ctx["hRmsR"]["out"],
        ctx["dynL"], ctx["dynR"],
        ctx["maxPkL"], ctx["maxPkR"],
        ctx["corr"], ctx["bal"],
        ctx["mL"]["overs"], ctx["mR"]["overs"],
        ctx["crest"], ctx["lufsM"], ctx["lufsS"],
    ]
    for i, src in enumerate(order):
        p.connect(src, 0, pk, i)
    mpre = p.obj("prepend meters", 800, 1390)
    p.connect(pk, 0, mpre, 0)
    p.connect(mpre, 0, ui, 0)
    # One outlet fanning out to two destinations has undefined order in Max,
    # and if the jsui were banged first it would draw the previous frame's
    # meters.  t b b fires right-to-left: build the list, then draw it.
    fo = p.obj("t b b", 800, 1330)
    p.connect(ft, 0, fo, 0)
    p.connect(fo, 1, pk, 0)
    p.connect(fo, 0, ui, 0)


def ui_return_wiring(p, ctx):
    X, Y = 40, 1400
    ui, eng = ctx["ui"], ctx["engine"]
    r = p.obj("route plotw reset pin idle", X, Y, nout=5)
    p.connect(ui, 0, r, 0)
    pw = p.obj("prepend plotw", X, Y + 30)
    p.connect(r, 0, pw, 0)
    p.connect(pw, 0, eng, 0)
    p.connect(r, 1, ctx["resetTrigger"], 0)

    # idle 1 -> drop to a 2 Hz heartbeat, which is still often enough to notice
    # the device becoming visible again.  idle 0 -> restore the chosen rate.
    g = p.obj("sel 1 0", X + 300, Y + 30, nout=3)
    p.connect(r, 3, g, 0)
    slow = p.msg("500", X + 300, Y + 60)
    p.connect(g, 0, slow, 0)
    p.connect(slow, 0, ctx["metro"], 1)
    # Restoring the chosen rate requires VISIBLE **and** AWAKE, and the two
    # gates below are what makes it an AND.  Before this, `idle 0` and
    # `visible 1` each banged the restore on their own, and that had a stable
    # failure mode: deselect the track (metro 200 ms, engines muted), wait the
    # 30 quiet frames for `idle 1` (metro 500 ms), then let ONE stray paint
    # through -- Live repainting the strip for a tooltip, a scroll, a mixer
    # refresh -- and `idle 0` restored 40 fps to a device nobody could see.
    # It could not recover either: `visible` is a `change -1`, so `visible 0`
    # would not re-fire until the user next changed track selection.  That is
    # exactly the reported symptom of the device costing MORE when its track is
    # not selected than when it is.
    #
    # `t b i` at each input, not a bare connection: the gate's control must be
    # set before the bang arrives, or the gate decides on the previous state.
    # Both gates start OPEN, which is the right pre-first-report default --
    # visible and awake.
    gVis = p.obj("gate 1 1", X + 380, Y + 90, nin=2, nout=1)
    gVis.d["varname"] = "gVisible"
    gAwake = p.obj("gate 1 1", X + 380, Y + 120, nin=2, nout=1)
    gAwake.d["varname"] = "gAwake"
    p.connect(gVis, 0, gAwake, 1)

    awk = p.obj("== 0", X + 300, Y + 90)
    p.connect(r, 3, awk, 0)
    awkt = p.obj("t b i", X + 300, Y + 120, nout=2)
    p.connect(awk, 0, awkt, 0)
    p.connect(awkt, 1, gAwake, 0)          # control first
    p.connect(awkt, 0, gVis, 1)            # then the bang, through both gates

    restore = p.obj("t b", X + 380, Y + 150)
    p.connect(gAwake, 0, restore, 0)
    ctx["fpsRestore"] = restore
    ctx["gVisible"] = gVis


def reset_wiring(p, ctx):
    """Everything accumulative clears from one place."""
    rt = ctx["resetTrigger"]
    X, Y = 1350, 560
    mrst = p.msg("reset", X, Y)
