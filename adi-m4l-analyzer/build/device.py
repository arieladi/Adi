def audio_path(p, ctx):
    Y = 46
    p.comment("AUDIO PATH -- plugin~ straight to plugout~. Everything below is a "
              "parallel read; nothing is inserted, so the output is bit-identical "
              "with zero added latency and the null test cancels in every mode.",
              20, Y - 22, fontsize=11)
    pin = p.obj("plugin~", 20, Y)
    pout = p.obj("plugout~", 20, Y + 200)
    p.connect(pin, 0, pout, 0)
    p.connect(pin, 1, pout, 1)
    ctx["plugin"] = pin


