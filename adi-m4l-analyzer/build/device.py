def running_max(p, x, y, src, init=-144.0):
    """
    A real running maximum.

    Max's `maximum` object only compares its two inlets -- it does not latch --
    so the stored value is maintained by feeding the output back into the cold
    right inlet.  A cold inlet produces no output, so the loop terminates.
    `t f f` fires right-first, which updates the store before the value is
    passed on.

    Returns (outlet_box, maximum_box); send a low float to maximum_box inlet 1
    to reset it.
    """
    mx = p.obj("maximum %s" % init, x, y)
    tf = p.obj("t f f", x, y + 26)
    p.connect(src, 0, mx, 0)
    p.connect(mx, 0, tf, 0)
    p.connect(tf, 1, mx, 1)      # right outlet fires first: update the store
    return tf, mx


def hold_block(p, x, y, src, tag):
    """
    bx_meter's hold bar: latch the highest value, then drop to the current
    value once the hold time has elapsed with nothing higher.

    The running max only emits a *new* value when a new high arrives, so
    `change` isolates exactly that event and uses it to restart the timer.
    When the timer expires the stored maximum is replaced by the latest value,
    which drops the bar.
    """
    out, mx = running_max(p, x, y, src)
    ch = p.obj("change -999.", x, y + 60)
    p.connect(out, 0, ch, 0)
    dl = p.obj("delay 3000", x, y + 86)
    dl.d["varname"] = "hold" + tag
    p.connect(ch, 0, dl, 0)
    cur = p.obj("f 0.", x + 170, y + 60)
    p.connect(src, 0, cur, 1)        # cold store of the latest value
    p.connect(dl, 0, cur, 0)         # timer fires -> push it...
    p.connect(cur, 0, mx, 1)         # ...into the store, dropping the bar
    return {"out": out, "max": mx, "delay": dl}


# ---------------------------------------------------------------------------
def build():
    p = Patcher(rect=(80, 80, 1700, 1150), presentation=True)
    # Live opens the device at this width; the Width menu resizes from here.
    p.devicewidth = float(DEV_W)
    ctx = {}
    p.comment("AVC Spectrum & Meter -- generated by build/device.py. "
              "Edit the generator, not this patch.", 20, 4, fontsize=12)
    audio_path(p, ctx)
    analysis_taps(p, ctx)
    spectrum_chain(p, ctx)
    capture_voices(p, ctx)
    goniometer(p, ctx)
    scope_capture(p, ctx)
    meter_chain(p, ctx)
    stats_chain(p, ctx)
    transport(p, ctx)
    timing(p, ctx)
    controls(p, ctx)
    presets(p, ctx)
    wiring(p, ctx)
    caption_layout(p, ctx)
    return p


