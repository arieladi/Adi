def transport(p, ctx):
    X, Y = 1350, 320
    p.comment("RESET -- clicking the plot, clicking the meters, the Reset button, "
              "or the transport going stopped -> playing. Never on stop, and never "
              "at a loop boundary (looping does not change is_playing).",
              X, Y - 22, fontsize=11)

    thisdev = p.obj("live.thisdevice", X, Y + 10)
    ctx["thisdevice"] = thisdev

    lp = p.obj("live.path live_set", X, Y + 60)
    obs = p.obj("live.observer @property is_playing", X, Y + 90, nin=2)
    p.connect(lp, 0, obs, 1)
    chg = p.obj("change -1", X, Y + 120)
    p.connect(obs, 0, chg, 0)
    playing = p.obj("sel 1", X, Y + 150, nout=2)
    p.connect(chg, 0, playing, 0)
    ctx["playing"] = playing

    rt = p.obj("t b b b", X, Y + 200)
    p.connect(playing, 0, rt, 0)
    ctx["resetTrigger"] = rt
    ctx["livepath"] = lp

    # ---- visibility ------------------------------------------------------
    # Live does not report whether a device's chain strip is drawn, but it does
    # report which track is SELECTED, and for this purpose they are the same
    # thing.  Built from live.path / live.object / live.observer rather than
    # LiveAPI inside the js object: these are patch objects whose wiring can be
    # inspected in the generated file, and the LiveAPI version silently fell
    # through to its fail-safe and left the device running at full cost.
    # live.thisdevice fans out to two chains, and a single outlet feeding two
    # destinations has undefined order in Max.  The device's own track id is the
    # COLD operand of the comparison, so it has to be in place before the
    # observer fires -- otherwise the first comparison runs against 0, decides
    # the device is invisible, and mutes it while it is being looked at.
    vseq = p.obj("t b b b", X + 420, Y - 20, nout=3)
    p.connect(thisdev, 0, vseq, 0)

    dp = p.obj("live.path this_device", X + 420, Y + 10)
    p.connect(vseq, 1, dp, 0)                      # right outlet: fires first
    dt = p.obj("t b l", X + 420, Y + 40)
    p.connect(dp, 0, dt, 0)
    dob = p.obj("live.object", X + 420, Y + 100, nin=2)
    p.connect(dt, 1, dob, 1)                       # id first, then ask
    gcp = p.msg("get canonical_parent", X + 560, Y + 70, w=150)
    p.connect(dt, 0, gcp, 0)
    p.connect(gcp, 0, dob, 0)
    rcp = p.obj("route canonical_parent", X + 420, Y + 130)
    p.connect(dob, 0, rcp, 0)
    rid1 = p.obj("route id", X + 420, Y + 160)
    p.connect(rcp, 0, rid1, 0)

    # Path STRAIGHT to the selected track, rather than to live_set view with an
    # observer on its selected_track property.  live.path's outlet 1 sends
    # `id nn` "whenever the id of the object at the current path changes", and
    # selecting a different track is exactly that -- so the path is itself the
    # notification and no live.observer is involved.
    #
    # This is how every Ableton device that watches the selection writes it: 15
    # of them in the factory packs use `live.path live_set view selected_track`,
    # and the bare `live.path live_set view` feeding an observer, which is what
    # this used to be, appears in none of them.  It never bound -- the on-screen
    # diagnostic showed the observer emitting nothing, ever, so the comparison
    # downstream never ran once and every feature hanging off it was dead.
    vp = p.obj("live.path live_set view selected_track", X + 700, Y + 10)
    p.connect(vseq, 0, vp, 0)          # bang -> outlet 0 gives the value at load
    rid2 = p.obj("route id", X + 700, Y + 100)
    p.connect(vp, 1, rid2, 0)          # outlet 1: every later selection change
    p.connect(vp, 0, rid2, 0)          # outlet 0: the initial read at load

    # my track vs the selected track; the device's own id is the cold operand
    same = p.obj("expr $i1 == $i2", X + 700, Y + 160, nin=2)
    p.connect(rid1, 0, same, 1)
    p.connect(rid2, 0, same, 0)
    vch = p.obj("change -1", X + 700, Y + 190)
    p.connect(same, 0, vch, 0)
    ctx["visible"] = vch

    # ---- the device's own power switch, written by the device itself --------
    # Device.is_active is read-only status; the switch is the device's
    # PARAMETER 0, the one Live names "Device On".  This whole construction is
    # copied from Ableton's own BeatSeeker.amxd, which switches itself off and
    # back on the same way -- `path this_device` -> `t getpath l` -> live.object
    # -> `append parameters 0` -> live.path.  live.object's getpath reply
    # already begins with the selector `path`, so appending to it produces
    # exactly the message the second live.path wants, with no route in between.
    #
    # It resolves off vseq's RIGHTMOST outlet, so the parameter's id is in place
    # before either the track comparison or the observer that drives it exists.
    apath = p.obj("live.path this_device", X + 1000, Y + 10)
    p.connect(vseq, 2, apath, 0)
    atrig = p.obj("t getpath l", X + 1000, Y + 40, nout=2)
    p.connect(apath, 0, atrig, 0)
    aob1 = p.obj("live.object", X + 1000, Y + 70, nin=2)
    p.connect(atrig, 1, aob1, 1)                   # id first, then the question
    p.connect(atrig, 0, aob1, 0)
    aapp = p.obj("append parameters 0", X + 1000, Y + 100)
    p.connect(aob1, 0, aapp, 0)
    apath2 = p.obj("live.path", X + 1000, Y + 130)
    p.connect(aapp, 0, apath2, 0)
    aob2 = p.obj("live.object", X + 1000, Y + 220, nin=2)
    # OUTLET 1, not 0.  live.path's outlet 0 sends `id nn` "in response to a
    # goto, bang or getid message ONLY"; outlet 1 sends it whenever the id at
    # the current path changes -- which is what setting the path does.  Reading
    # outlet 0 here bound nothing, so live.object had no target and every
    # `set value` went nowhere, silently.  BeatSeeker reads outlet 1 too.
    p.connect(apath2, 1, aob2, 1)

    # ---- diagnostic tap ------------------------------------------------
    # Four read-only taps onto the settings screen.  The chain has now failed
    # twice for reasons that produce NO error anywhere -- a live.object bound to
    # nothing accepts `set value` and discards it in silence -- so the next step
    # is to see the numbers rather than reason about them.  Pure observers: they
    # add a destination to outlets that already fan out, and nothing downstream
    # depends on their order.
    aid = p.obj("route id", X + 1000, Y + 160)
    p.connect(apath2, 1, aid, 0)
    for src, out, tag, dx in ((aid, 0, "dbgpar", 0), (rid1, 0, "dbgtrk", 150),
                              (rid2, 0, "dbgsel", 300), (vch, 0, "dbgvis", 450)):
        pre = p.obj("prepend " + tag, X + 1000 + dx, Y + 260)
        p.connect(src, out, pre, 0)
        ctx.setdefault("dbgTaps", []).append(pre)

    # Auto gates it.  With Auto off the chain is dead and the power button is
    # the user's again.
    agate = p.obj("gate 1 1", X + 1220, Y + 160, nin=2, nout=1)
    agate.d["varname"] = "autoGate"
    ctx["autoGate"] = agate
    p.connect(ctx["visible"], 0, agate, 1)

    # deferlow is REQUIRED, not tidiness: this value arrives inside a
    # live.observer notification, and Live refuses to let a notification trigger
    # a change.  BeatSeeker defers for the same reason.
    adef = p.obj("deferlow", X + 1220, Y + 190)
    p.connect(agate, 0, adef, 0)
    aset = p.msg("set value $1", X + 1220, Y + 220, w=96)
    p.connect(adef, 0, aset, 0)
    p.connect(aset, 0, aob2, 0)


