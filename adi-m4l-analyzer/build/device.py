"""
Builds the AVC Spectrum & Meter device (.amxd + .maxpat).

Structure mirrors the signal flow:

    audio_path()      plugin~ straight to plugout~.  Nothing else touches it.
    analysis_taps()   parallel taps: L, R, Mid, Side, plus the two engine sources
    spectrum_chain()  matrix -> planemap -> jit.gen reduction -> jit.spill -> jsui
    meter_chain()     all metering and ballistics, in MSP
    stats_chain()     clip counters, max crest factor, LUFS M/S
    transport()       reset rules, including the stopped -> playing edge
    timing()          redraw clock and its visibility gate
    controls()        live.* parameters, every one of them "Stored Only"
    presets()
    wiring()          ties it together

Everything the device shows is measured in MSP or reduced in Jitter; the two js
objects only configure, and jsui only draws.
"""

