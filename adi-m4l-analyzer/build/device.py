def caption_layout(p, ctx):
    """
    Tell the jsui where every control sits, so it can label them.

    The positions live here because this is what places the controls, and the
    words live in the jsui because that is what draws them -- neither file has
    to know the other's half.  Sent as three message boxes rather than 33: a
    message box holds a comma-separated list, and this fires once at load.
    """
    X, Y = 20, 2500
    p.comment("CAPTION LAYOUT -- tells the jsui where each control is so the "
              "settings screen can label it", X, Y - 22, fontsize=11)
    rows = {}
    for longname, px, py, w in ctx.get("capLayout", []):
        if py < 20:
            continue          # the View tab is its own vertical strip
        rows.setdefault(py, []).append((px, w, longname))
    trig = p.obj("t" + " b" * len(rows), X, Y, nout=len(rows))
    p.connect(ctx["thisdevice"], 0, trig, 0)
    for i, py in enumerate(sorted(rows)):
        parts = ["capbox %s %d %d %d" % (nm, int(px), int(w), int(py))
                 for px, w, nm in sorted(rows[py])]
        m = p.msg(", ".join(parts), X, Y + 40 + i * 30, w=760)
        p.connect(trig, i, m, 0)
        p.connect(m, 0, ctx["ui"], 0)

    # ...and a tell-tale from every control, so the settings screen can say what
    # the thing you just moved actually does.  It has to come from the PATCH
    # rather than from the jsui's own setters: half these controls are wired to
    # the analysis engine and never reach the drawing layer at all, so hooking
    # the setters would have explained the display options and stayed silent on
    # exactly the ones that are hard to guess.
    for j, (box, longname, py) in enumerate(ctx.get("capBoxes", [])):
        if py < 20:
            continue
        t = p.msg("touchedby " + longname, X + 800 + (j % 4) * 150,
                  Y + 40 + (j // 4) * 26, w=140)
        p.connect(box, 0, t, 0)
        p.connect(t, 0, ctx["ui"], 0)


