# 2. Analysis taps
# ---------------------------------------------------------------------------
def analysis_taps(p, ctx):
    pin = ctx["plugin"]
    X, Y = 300, 46
    p.comment("ANALYSIS TAPS (parallel)", X, Y - 22, fontsize=11)

    sm = p.obj("+~", X, Y + 30)
    p.connect(pin, 0, sm, 0)
    p.connect(pin, 1, sm, 1)
    mid = p.obj("*~ 0.5", X, Y + 56)
    p.connect(sm, 0, mid, 0)

    df = p.obj("-~", X + 130, Y + 30)
    p.connect(pin, 0, df, 0)
    p.connect(pin, 1, df, 1)
    side = p.obj("*~ 0.5", X + 130, Y + 56)
    p.connect(df, 0, side, 0)

    # selector~ index 0 is silence; 1..5 are Sum / L / R / Mid / Side
    # Second argument = initially-open inlet, so analysis and metering still
    # see audio even if a routing message never arrives.  Defaults match the
    # default Channel mode (L+R overlaid): A = L, B = R.
    srcA = p.obj("selector~ 5 1", X, Y + 104, nin=6)   # default Sum
    srcB = p.obj("selector~ 5 0", X, Y + 134, nin=6)   # default off
    for s in (srcA, srcB):
        p.connect(mid, 0, s, 1)
        p.connect(pin, 0, s, 2)
        p.connect(pin, 1, s, 3)
        p.connect(mid, 0, s, 4)
        p.connect(side, 0, s, 5)
    srcA.d["varname"] = "srcA"
    srcB.d["varname"] = "srcB"
    p.comment("srcA / srcB -- avc.engine.js connects the runtime pfft~ to these",
              X + 190, Y + 119)

    mtrL = p.obj("selector~ 2 1", X + 520, Y + 104, nin=3)
    mtrR = p.obj("selector~ 2 1", X + 520, Y + 134, nin=3)
    p.connect(pin, 0, mtrL, 1)
    p.connect(mid, 0, mtrL, 2)
    p.connect(pin, 1, mtrR, 1)
    p.connect(side, 0, mtrR, 2)
    p.comment("metering source: L/R or Mid/Side", X + 660, Y + 119)

    ctx.update(mid=mid, side=side, srcA=srcA, srcB=srcB, mtrL=mtrL, mtrR=mtrR)


