# 4. Metering, in MSP
# ---------------------------------------------------------------------------
def meter_block(p, x, y, tag, src, ctx):
    """
    One metering channel.

    Peak is taken with peakamp~, which reports the largest sample since the
    previous report, so no peak between UI frames is ever missed.  A separate
    abs~ -> slide~ path gives the bar its ballistics.  RMS squares the
    *weighted* signal, one-poles it with independent integration and release
    times, and roots the result.
    """
    out = {}
    pk = p.obj("peakamp~ 0", x, y)
    p.connect(src, 0, pk, 0)
    pkdb = p.obj("atodb", x, y + 26)
    p.connect(pk, 0, pkdb, 0)
    out["peakRaw"], out["peakBang"] = pkdb, pk

    ab = p.obj("abs~", x + 150, y)
    p.connect(src, 0, ab, 0)
    psl = p.obj("slide~ 1 1000", x + 150, y + 26)
    psl.d["varname"] = "pkSlide" + tag
    ctx.setdefault("slides", {})["pkSlide" + tag] = psl
    p.connect(ab, 0, psl, 0)
    psn = p.obj("snapshot~", x + 150, y + 52)
    p.connect(psl, 0, psn, 0)
    pbar = p.obj("atodb", x + 150, y + 78)
    p.connect(psn, 0, pbar, 0)
    out["peakBar"], out["peakSnap"] = pbar, psn

    # weighting cascade -- measurement only, never in the audio path
    w = src
    for i in range(3):
        b = p.obj("biquad~ 1. 0. 0. 0. 0.", x + 330, y + i * 26)
        b.d["varname"] = "w%s%d" % (tag, i + 1)
        p.connect(w, 0, b, 0)
        w = b

    # A true sliding-window RMS, not a one-pole.
    #
    # "Integration time = time to fall 20 dB" makes a one-pole with a ~33 ms
    # time constant at the 300 ms default, which lurches with every kick.
    # bx_meter's RMS is a window average and sits steady, so this is
    # average~ in rms mode with the window set to the integration time --
    # which is also what "RMS" actually means.  Release now shapes the peak
    # bar only; a window average has no separate release.
    rav = p.obj("average~ 192000 rms", x + 330, y + 92)   # up to 2 s at 96 kHz
    rav.d["varname"] = "rmsAvg" + tag
    ctx.setdefault("rmswin", []).append(rav)
    p.connect(w, 0, rav, 0)
    rsn = p.obj("snapshot~", x + 330, y + 144)
    p.connect(rav, 0, rsn, 0)
    rdb = p.obj("atodb", x + 330, y + 196)
    p.connect(rsn, 0, rdb, 0)
    # AES-17 / sine reference: +3.0103 dB, so a full-scale SINE reads 0.0 dB
    # RMS rather than -3.01.  Measured simultaneously on the same programme
    # material, SPAN read -6.6 and bx_meter -3.3 -- the whole difference is
    # this constant, and bx_meter is the reference for the metering block.
    # It is applied here, in MSP, so the RMS bar, the RMS hold bar, Dynamic
    # and Max Crest Factor all inherit it consistently.  Peak deliberately
    # does NOT: bx_meter's Peak reads the same -0.1 that a plain dBFS peak
    # does, and an over is a property of the signal, not of the RMS scale.
    rref = p.obj("+ 3.0103", x + 330, y + 222)
    p.connect(rdb, 0, rref, 0)
    out["rms"], out["rmsSnap"] = rref, rsn

    # 50 ms window RMS, used only for Max Crest Factor
    r50 = p.obj("average~ 9600 rms", x + 540, y + 92)
    r50.d["varname"] = "rms50" + tag
    ctx.setdefault("rms50win", []).append(r50)
    p.connect(w, 0, r50, 0)
    s50 = p.obj("snapshot~", x + 540, y + 144)
    p.connect(r50, 0, s50, 0)
    d50 = p.obj("atodb", x + 540, y + 196)
    p.connect(s50, 0, d50, 0)
    d50r = p.obj("+ 3.0103", x + 540, y + 222)   # same reference as the main RMS
    p.connect(d50, 0, d50r, 0)
    out["rms50"], out["rms50Snap"] = d50r, s50

    # sample-peak clip counter: count over *events*, not samples.
    # Fed from abs~, NOT from src: src is the signed signal, and a sample of
    # -1.0 is not >= 0.999, so roughly half of all clipped samples -- every
    # negative-going one -- went uncounted.
    ov = p.obj(">=~ 0.999", x + 700, y)
    p.connect(ab, 0, ov, 0)
    ed = p.obj("edge~", x + 700, y + 26)
    p.connect(ov, 0, ed, 0)
    cnt = p.obj("f 0", x + 700, y + 80)
    inc = p.obj("+ 1", x + 700, y + 106)
    p.connect(ed, 0, cnt, 0)
    p.connect(cnt, 0, inc, 0)
    p.connect(inc, 0, cnt, 1)
    # Read the counter from `+ 1`, not from `f`: edge~'s bang hits f's hot
    # inlet, which emits the STORED value before `+ 1` writes the new one
    # back, so f reports one less than the number of overs -- and a single
    # clipped sample reported 0.  Reset still targets f's cold inlet.
    out["overs"], out["oversReset"] = inc, cnt
    return out


def capture_voices(p, ctx):
    """
    The goniometer and scope writes, each in a poly~ voice of its own so they
    can be switched off independently.

    They are the only audio-rate Jitter writes in the device -- four jit.poke~
    storing one float per sample per channel -- and until now they ran whether
    or not their view was on screen, because MSP gives no way to disable a
    single object.  poly~ does: `mute 1 1` stops signal processing inside the
    instance, `mute 1 0` starts it again.  applyMute() in avc.engine.js drives
    both from what is actually on screen: the goniometer draws in every view but
    the settings screen, the scope only in OSC, and neither draws while the
    device is not being looked at.

    The matrices themselves stay in the parent -- they are read there, once a
    frame, by jit.spill -- and only the writing moves.  Their names travel in as
    poly~ arguments, so #0 stays resolved in the parent, where it means
    something.
    """
    X, Y = 20, 1985
    p.comment("CAPTURE VOICES -- the only audio-rate Jitter writes in the "
              "device, isolated so each can be muted when nothing reads it",
              X, Y - 22, fontsize=11)
    pin = ctx["plugin"]
    for key, text in (("capgonio", "poly~ avc.capgonio 1 args #0_gonio"),
                      ("capscope", "poly~ avc.capscope 1 args #0_scope #0_raw")):
        v = p.obj(text, X + (0 if key.endswith("gonio") else 300), Y,
                  nin=3, nout=1)
        v.d["varname"] = key
        p.connect(pin, 0, v, 0)
        p.connect(pin, 1, v, 1)
        ctx[key] = v


def goniometer(p, ctx):
    """
    RME Totalyser-style goniometer: L against R, rotated 45 degrees so mono
    reads as a vertical line up the M axis and out-of-phase content spreads
    along S.

    The samples reach the drawing layer the same way the spectrum does -- a
    jit.matrix written by jit.poke~ at audio rate and read out with jit.spill
    once a frame -- because pulling 512 samples per frame through the control
    domain any other way is not affordable.  phasor~ supplies the write index:
    one cycle per 512 samples at 44.1 kHz, which is 11.6 ms of audio in the
    window, about what a hardware goniometer's afterglow shows.  The rate is
    fixed rather than tracking the sample rate: at 96 kHz the window is 5.8 ms
    instead, which changes nothing about what the display means.
    """
    X, Y = 20, 2050
    p.comment("GONIOMETER -- L and R interleaved into one matrix at audio rate, "
              "spilled to the jsui as a single list per redraw", X, Y - 22,
              fontsize=11)
    pin = ctx["plugin"]
    gm = p.obj("jit.matrix #0_gonio 1 float32 1024 1", X, Y)
    gm.d["varname"] = "gonio"

    # The writes happen in the capture voice (see capture_voice); this end only
    # allocates the matrix and reads it out.  ONE plane with L at even cells and
    # R at odd, not two planes: two jit.spill objects hanging off the same
    # matrix outlet output in undefined order, and if R went first the JS paired
    # L from one frame with R from the next -- cross-frame L and R are
    # uncorrelated, so a mono signal drew the same scattered ball as a wide one.
    # Interleaving makes the pairing a property of the data instead of of
    # message order.
    sp = p.obj("jit.spill @plane 0 @listlength 1024", X, Y + 130)
    sp.d["varname"] = "gspill"
    p.connect(gm, 0, sp, 0)
    pre = p.obj("prepend g0", X + 300, Y + 130)
    p.connect(sp, 0, pre, 0)
    ctx["gspills"] = [pre]
    ctx["gonioMat"] = gm


def scope_capture(p, ctx):
    """
    Capture for the oscilloscope: a PEAK ENVELOPE over a long window, not raw
    samples over a short one.

    The sweep is ONE BAR, locked to Live's transport: phasor~ takes a
    tempo-relative interval and follows the named transport, so `1n` is one
    cycle per whole note.  The kick on beat 1 therefore lands on the left edge
    every time instead of the window wandering against the music.

    Storing every sample for a bar is ~73000 floats a frame crossing into the
    drawing layer; storing every 70th would alias transients away completely --
    a kick would land between samples and vanish.  So abs~ feeds a slide~ with
    instant attack and a slow decay, and the write index steps through the
    matrix slowly enough that ~70 consecutive samples land in the same cell,
    each overwriting the last.  Because the envelope rises instantly and decays
    slowly, the value left in the cell is close to that group's PEAK.  The decay
    is set to roughly twice a group so a transient at the start of one is still
    ~60% of its height at the end; shorter and transients get lost between
    writes, longer and they smear across neighbouring columns.

    Interleaved L/R in one plane for the same reason the goniometer is: two
    spills off one matrix outlet fire in undefined order.
    """
    X, Y = 20, 2250
    p.comment("SCOPE CAPTURE -- peak envelope over ~1.5 s, one plane, "
              "L at even cells and R at odd, one bar per sweep", X, Y - 22,
              fontsize=11)
    pin = ctx["plugin"]
    sm = p.obj("jit.matrix #0_scope 1 float32 2048 1", X, Y)
    sm.d["varname"] = "scopeMat"

    # Written from the capture voice; interleaved L/R in one plane for the same
    # reason the goniometer is.
    sp = p.obj("jit.spill @plane 0 @listlength 2048", X, Y + 180)
    sp.d["varname"] = "sspill"
    p.connect(sm, 0, sp, 0)
    pre = p.obj("prepend s0", X + 300, Y + 180)
    p.connect(sp, 0, pre, 0)
    ctx["scopeMat"], ctx["scopeSpill"] = sm, pre

    # The fast scope's raw trace, captured and read the same way but on its own
    # free-running sweep -- see build/capture.py.
    rm = p.obj("jit.matrix #0_raw 1 float32 512 1", X + 520, Y)
    rm.d["varname"] = "rawMat"
    rsp = p.obj("jit.spill @plane 0 @listlength 512", X + 520, Y + 180)
    rsp.d["varname"] = "rspill"
    p.connect(rm, 0, rsp, 0)
    rpre = p.obj("prepend r0", X + 520, Y + 210)
    p.connect(rsp, 0, rpre, 0)
    ctx["rawMat"], ctx["rawSpill"] = rm, rpre


def meter_chain(p, ctx):
    X, Y = 20, 660
    p.comment("METERING -- measurement and ballistics are MSP. Only "
              "already-measured numbers cross into the control domain.",
              X, Y - 22, fontsize=11)
    mL = meter_block(p, X, Y, "L", ctx["mtrL"], ctx)
    mR = meter_block(p, X, Y + 250, "R", ctx["mtrR"], ctx)
    ctx["mL"], ctx["mR"] = mL, mR

    HY = Y + 520
    p.comment("hold bars -- 3 s latch and drop", X, HY - 20, fontsize=11)
    ctx["hPkL"] = hold_block(p, X, HY, mL["peakRaw"], "PkL")
    ctx["hPkR"] = hold_block(p, X + 360, HY, mR["peakRaw"], "PkR")
    ctx["hRmsL"] = hold_block(p, X + 720, HY, mL["rms"], "RmsL")
    ctx["hRmsR"] = hold_block(p, X + 1080, HY, mR["rms"], "RmsR")

    NY = HY + 150
    p.comment("numeric maxima since reset, and Peak - RMS", X, NY - 20)
    ctx["maxPkL"], ctx["maxPkLmx"] = running_max(p, X, NY, mL["peakRaw"])
    ctx["maxPkR"], ctx["maxPkRmx"] = running_max(p, X + 200, NY, mR["peakRaw"])

    # Peak minus RMS, then smoothed.  The difference of two already-smoothed
    # values still twitches because the peak envelope moves faster than the RMS
    # window; bx_meter's Dynamic sits noticeably steadier.  `slide` is the
    # control-rate one-pole, so 4 is a ~100 ms time constant at the default
    # 40 fps.  It shapes the READING only -- peak and RMS are untouched.
    dl = p.obj("!- 0.", X + 420, NY)
    p.connect(mL["rms"], 0, dl, 0)
    p.connect(mL["peakBar"], 0, dl, 1)
    ctx["dynL"] = p.obj("slide 4 4", X + 420, NY + 30)
    p.connect(dl, 0, ctx["dynL"], 0)
    dr = p.obj("!- 0.", X + 580, NY)
    p.connect(mR["rms"], 0, dr, 0)
    p.connect(mR["peakBar"], 0, dr, 1)
    ctx["dynR"] = p.obj("slide 4 4", X + 580, NY + 30)
    p.connect(dr, 0, ctx["dynR"], 0)

    correlation_balance(p, ctx, X, NY + 90)


def correlation_balance(p, ctx, X, Y):
    """
    Correlation over 500 ms and stereo balance over 3 s, both one-poled in MSP.
        corr = E[LR] / sqrt(E[L^2] E[R^2])
    Balance is the dB ratio of the two channel powers, negative when left is
    louder, matching bx_meter's sign convention.

    slide~'s coefficient IS the time constant in samples, so it has to track
    the sample rate like every other ballistic in the device.  All five
    integrators were previously hard-coded to 22050 -- right only at 44.1 kHz,
    and applied to the balance pair as well, so the documented 3 s balance was
    actually running at 500 ms (and at 250 ms at 96 kHz).
    """
    p.comment("correlation (500 ms) and stereo balance (3 s)", X, Y - 20, fontsize=11)
    pin = ctx["plugin"]
    lr = p.obj("*~", X, Y)
    p.connect(pin, 0, lr, 0)
    p.connect(pin, 1, lr, 1)
    ll = p.obj("*~", X + 130, Y)
    p.connect(pin, 0, ll, 0)
    p.connect(pin, 0, ll, 1)
    rr = p.obj("*~", X + 260, Y)
    p.connect(pin, 1, rr, 0)
    p.connect(pin, 1, rr, 1)

    snaps = {}
    specs = [("lr", lr, "cs_lr", "corr"), ("ll", ll, "cs_ll", "corr"),
             ("rr", rr, "cs_rr", "corr"),
             ("llB", ll, "cs_llB", "bal"), ("rrB", rr, "cs_rrB", "bal")]
    ctx["corrSlides"], ctx["balSlides"] = [], []
    for i, (name, srcb, vn, grp) in enumerate(specs):
        sl = p.obj("slide~ 22050 22050", X + i * 140, Y + 32)
        sl.d["varname"] = vn
        ctx["corrSlides" if grp == "corr" else "balSlides"].append(sl)
        p.connect(srcb, 0, sl, 0)
        sn = p.obj("snapshot~", X + i * 140, Y + 58)
        p.connect(sl, 0, sn, 0)
        snaps[name] = sn

    # No ternary: Max's expr documents + - * / %, the bitwise/logical set and
    # comparisons, but NOT ?: -- every ternary expr in this device silently
    # never produced output.  max() IS a documented expr function, so the
    # divide-by-zero guard goes there instead.
    #
    # The guard is spelled out in full rather than as 1e-20: exponent notation
    # appears nowhere in expr's documentation, and measuring the built device
    # showed the correlation bar sitting at exactly 0.0 -- pack's creation
    # default, i.e. this object was never producing output at all.  That is
    # the "correlation meter never moves" report.
    corr = p.obj("expr $f1/sqrt(max($f2*$f3, 0.0000000001))", X, Y + 94, nin=3)
    p.connect(snaps["lr"], 0, corr, 0)
    p.connect(snaps["ll"], 0, corr, 1)
    p.connect(snaps["rr"], 0, corr, 2)

    bal = p.obj("expr 10.*log10(($f2+0.0000000001)/($f1+0.0000000001))", X + 460, Y + 94, nin=2)
    p.connect(snaps["llB"], 0, bal, 0)
    p.connect(snaps["rrB"], 0, bal, 1)

    ctx["corr"], ctx["bal"], ctx["corrSnaps"] = corr, bal, snaps


