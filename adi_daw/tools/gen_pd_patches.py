#!/usr/bin/env python3
"""Generate adi_daw's Pd modules -- ADR-0096.

    python adi_daw/tools/gen_pd_patches.py            write adi_daw/pd/*.pd
    python adi_daw/tools/gen_pd_patches.py --check    exit 1 if they are stale

Generated, not hand-written, because a Pd file wires objects together by their
CREATION INDEX (`#X connect 4 0 7 1`), comments included. Inserting one object by
hand silently re-points every connection after it, and nothing complains until
the patch is opened. A generator counts for us.

The DSP maths does not live here. It lives in src/adi/dsp/, where it is tested:
the EQ receives coefficients the host computed with dsp::toPd(), and the limiter
and RMSC mirror dsp::LookaheadLimiter and dsp::RingModSidechain. These patches
are UNRUN on the machine that generated them -- no Pd there -- and are checked
structurally by adi_dsp_tests until libpd lands and they can be compared against
the reference sample for sample.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'pd')


class Patch:
    """One Pd canvas. `obj` returns the new object's index, so a connection is
    made by name, never by counting."""

    def __init__(self, w=900, h=700):
        self.lines = ['#N canvas 0 50 %d %d 12;' % (w, h)]
        self.n = 0

    def _add(self, line):
        self.lines.append(line)
        i = self.n
        self.n += 1
        return i

    def obj(self, x, y, text):
        return self._add('#X obj %d %d %s;' % (x, y, text))

    def msg(self, x, y, text):
        return self._add('#X msg %d %d %s;' % (x, y, text))

    def text(self, x, y, text):
        # A comment IS an object as far as the numbering goes.
        return self._add('#X text %d %d %s;' % (x, y, text))

    def connect(self, a, outlet, b, inlet):
        self.lines.append('#X connect %d %d %d %d;' % (a, outlet, b, inlet))

    def subpatch(self, x, y, name, child):
        """Embed `child` as [pd name]. Inside it the numbering restarts at 0;
        in THIS canvas the whole subpatch is one object, created by the
        restore line -- which is why it is added last. A subpatch shares its
        parent's $0, unlike an abstraction."""
        self.lines.append('#N canvas 0 50 450 300 %s 0;' % name)
        self.lines.extend(child.lines[1:])
        return self._add('#X restore %d %d pd %s;' % (x, y, name))

    def render(self):
        return '\n'.join(self.lines) + '\n'


def pd_comment(s):
    # Pd comments cannot hold bare commas or semicolons.
    return s.replace(',', ' \\,').replace(';', ' \\;')


