"""Generate immutable RGB8 display tables from pinned public scientific data.

No Python package is imported or executed from the input directory. Sources are
verified against the bundled provenance before parsing .npy or literal AST data.
"""
import argparse
import ast
import hashlib
import json
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
NOTICE = ROOT / "third_party_notices" / "analysis_palettes"
NAMES = ("gray amber amethyst apple arctic bubblegum chroma cividis cosmic "
         "cubehelix dusk eclipse ember emerald fall flamingo freeze gem "
         "ghostlight gothic horizon inferno jungle lavender lilac magma mako "
         "neon nuclear ocean pepper plasma rainforest rocket sapphire savanna "
         "sepia sunburst swamp torch toxic tree tropical turbo viridis voltage").split()


def numpy_rows(data):
    if data[:6] != b"\x93NUMPY" or data[6:8] != b"\x01\x00":
        raise ValueError("Expected pinned NumPy v1 data")
    length = struct.unpack_from("<H", data, 8)[0]
    header = ast.literal_eval(data[10:10 + length].decode("ascii"))
    if header != {"descr": "<f8", "fortran_order": False, "shape": (256, 3)}:
        raise ValueError("Unexpected palette array layout")
    values = struct.unpack("<768d", data[10 + length:])
    return [values[i:i + 3] for i in range(0, len(values), 3)]


def literal_tables(data):
    result = {}
    names = {"_" + name + suffix: name for name in NAMES for suffix in ("_data", "_lut")}
    for node in ast.parse(data.decode("utf-8")).body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in names:
                    result[names[target.id]] = ast.literal_eval(node.value)
    return result


def generate(source_dir):
    provenance = json.loads((NOTICE / "PROVENANCE.json").read_text(encoding="utf-8"))
    sources = {}
    for entry in provenance["sources"]:
        data = (source_dir / entry["file"]).read_bytes()
        if hashlib.sha256(data).hexdigest() != entry["sha256"]:
            raise ValueError("Source hash mismatch: " + entry["file"])
        sources[entry["file"]] = data
    tables = {}
    for filename in ("matplotlib-colours.py", "seaborn-colours.py"):
        tables.update(literal_tables(sources[filename]))
    for name in NAMES:
        if name not in tables and name not in ("gray", "cubehelix"):
            tables[name] = numpy_rows(sources[name + ".npy"])
    tables["gray"] = [(i / 255, i / 255, i / 255) for i in range(256)]
    cubehelix = []
    for i in range(256):
        x = i / 255
        a = x * (1 - x) / 2
        phi = 2 * math.pi * (.5 / 3 - 1.5 * x)
        cubehelix.append(tuple(max(0, min(1, x + a * (p * math.cos(phi) + q * math.sin(phi))))
                              for p, q in ((-.14861, 1.78277), (-.29227, -.90649), (1.97294, 0))))
    tables["cubehelix"] = cubehelix
    lines = ["// SPDX-License-Identifier: BSD-3-Clause AND LicenseRef-Matplotlib",
             "// Generated by tools/generate_analysis_palettes.py; do not hand edit.",
             "// All 256 upstream samples retained, quantized to RGB8 (nearest, ties upward).",
             "// Full licenses/provenance: third_party_notices/analysis_palettes/.",
             "#pragma once", "#include <array>", "#include <cstdint>", "#include <string_view>",
             "namespace adi::ui::palettes::data {",
             "inline constexpr std::array<std::string_view, 47> ids{",
             '    "adi", ' + ", ".join('"' + name + '"' for name in NAMES) + "};",
             "inline constexpr std::array<std::array<std::uint32_t, 256>, 46> rgb{{"]
    for name in NAMES:
        values = tables[name]
        if len(values) != 256:
            raise ValueError("Expected 256 samples: " + name)
        packed = []
        for row in values:
            if len(row) != 3 or not all(math.isfinite(v) and 0 <= v <= 1 for v in row):
                raise ValueError("Invalid RGB data: " + name)
            red, green, blue = (int(v * 255 + .5) for v in row)
            packed.append((red << 16) | (green << 8) | blue)
        lines.append("    {{ // " + name)
        for first in range(0, 256, 8):
            lines.append("        " + ", ".join(f"0x{v:06x}u" for v in packed[first:first + 8]) + ",")
        lines.append("    }},")
    lines += ["}};", "} // namespace adi::ui::palettes::data", ""]
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True, help="Directory containing pinned public source files")
    parser.add_argument("--output", type=Path, default=ROOT / "src/adi/ui/palettes/data.hpp")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = generate(args.source_dir)
    if args.check:
        if args.output.read_bytes().replace(b"\r\n", b"\n") != data:
            raise SystemExit("Generated palette data differs")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(data)
    print(f"46 palettes / 11,776 RGB entries; SHA256 {hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    main()
