const char* toString(Absence a) {
    switch (a) {
        case Absence::Rejected:    return "rejected";
        case Absence::Note:        return "note";
        case Absence::NotASetting: return "not a setting";
        case Absence::Backlog:     return "backlog";
        case Absence::Wish:        return "wish";
    }
    return "?";
}

