const Theme &themeFor(ThemeId id) {
    switch (id) {
    case ThemeId::MidGrey:
        return kMidGrey;
    case ThemeId::Light:
        return kLight;
    case ThemeId::MixView:
        return kMixView;
    case ThemeId::Dark:
        break;
    }
    return kDark;
}
std::string_view themeName(ThemeId id) {
    switch (id) {
    case ThemeId::MidGrey:
        return "midgrey";
    case ThemeId::Light:
        return "light";
    case ThemeId::MixView:
        return "mixview";
    case ThemeId::Dark:
        break;
    }
    return "dark";
}
ThemeId themeFromSetting(std::string_view word) {
    for (const auto id : kThemes)
        if (themeName(id) == word)
            return id;
    return ThemeId::Dark; // "os", and anything unknown
}
